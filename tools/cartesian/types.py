"""Emit compact Cartesian tensors with an optional full rank-two block."""


def indices(rank):
    return [(x, rank - x, 0) for x in range(rank + 1)] + [
        (x, rank - 1 - x, 1) for x in range(rank)
    ]


def component_name(index):
    return 'm' if index == (0, 0, 0) else ''.join(
        axis * count for axis, count in zip('xyz', index)
    )


def names(degree, quadrupoleTrace=True):
    result = [component_name(index) for rank in range(degree + 1)
              for index in indices(rank)]
    if quadrupoleTrace and degree >= 2:
        result.append('zz')
    return result


def generate_types(max_degree, quadrupoleTrace=True):
    extra = ' + (degree >= 2 ? 1 : 0)' if quadrupoleTrace else ''
    count = '(degree + 1) * (degree + 1)' + extra
    lines = [
        '// Generated by tools/generate_fmm.py. Do not edit.',
        '#pragma once', '',
        '#include <type_traits>', '',
        '#include <cosmictiger/core/containers.hpp>', '',
        'namespace cosmictiger::gravity::cartesian {',
        'namespace detail {',
        'struct CoefficientArrayInit {};',
        'template <class Real, int degree> struct CoefficientFields;',
    ]
    for degree in sorted({max_degree - 1, max_degree}):
        fields = names(degree, quadrupoleTrace)
        lines += [f'template <class Real> struct CoefficientFields<Real, {degree}> {{',
                  '    union {', '        struct {']
        lines += [f'            Real {field};' for field in fields]
        lines += ['        };', f'        Real coefficients[{len(fields)}];',
                  '    };',
                  '    /// Leave scalar coefficient initialization to the caller.',
                  '    CUDA_EXPORT CoefficientFields() = default;',
                  '    /// Value-initialize the coefficient array as the active union member.',
                  '    CUDA_EXPORT explicit CoefficientFields(CoefficientArrayInit)',
                  '        : coefficients() {}', '};', '']
        lines += [f'static_assert(sizeof(CoefficientFields<float, {degree}>) == '
                  f'{len(fields)} * sizeof(float));']
    lines += [
        '// Preserve trivial scalar transport records. SIMD packs can have',
        '// non-trivial copy operations, which delete the implicit union copies.',
        'template <class Real, int degree, bool trivialCopy = std::is_trivially_copyable_v<Real>>',
        'struct CoefficientStorage : CoefficientFields<Real, degree> {};',
        'template <class Real, int degree>',
        'struct CoefficientStorage<Real, degree, false> : CoefficientFields<Real, degree> {',
        '    /// Initialize coefficient storage for a nontrivially copyable scalar or SIMD type.',
        '    CUDA_EXPORT CoefficientStorage()',
        '        : CoefficientFields<Real, degree>(CoefficientArrayInit()) {}',
        '    /// Copy each coefficient while preserving the active array member.',
        '    CUDA_EXPORT CoefficientStorage(CoefficientStorage const& other)',
        '        : CoefficientStorage() {',
        f'        for (int i = 0; i < {count}; i++) {{',
        '            this->coefficients[i] = other.coefficients[i];',
        '        }',
        '    }',
        '    /// Assign each coefficient without relying on a deleted union copy operation.',
        '    CUDA_EXPORT CoefficientStorage& operator=(CoefficientStorage const& other) {',
        f'        for (int i = 0; i < {count}; i++) {{',
        '            this->coefficients[i] = other.coefficients[i];',
        '        }',
        '        return *this;',
        '    }',
        '};',
        'template <class Real, int degree>',
        'struct Coefficients : CoefficientStorage<Real, degree> {',
        '    static constexpr int kDegree_ = degree;',
        f'    static constexpr int kSize_ = {count};',
        '    /// Return the number of stored independent Cartesian coefficients.',
        '    CUDA_EXPORT constexpr int size() const { return kSize_; }',
        '    /// Map a stored Cartesian component to its compact coefficient slot.',
        '    CUDA_EXPORT static constexpr int index(int nx, int ny, int nz) {',
        '        int const rank = nx + ny + nz;',
        *(['        if (rank == 2 && nz == 2) { return (degree + 1) * (degree + 1); }']
          if quadrupoleTrace else []),
        '        return rank * rank + (nz == 0 ? nx : rank + 1 + nx);',
        '    }',
        '    /// Fill every independent coefficient with the supplied value.',
        '    CUDA_EXPORT Coefficients& operator=(Real const& value) {',
        '        for (int i = 0; i < kSize_; i++) { this->coefficients[i] = value; }',
        '        return *this;',
        '    }',
        '    /// Access a mutable compact coefficient, checking the index when CHECK_BOUNDS is enabled.',
        '    CUDA_EXPORT Real& operator[](int i) {',
        '#ifdef CHECK_BOUNDS',
        '        DO_BOUNDS_CHECK(i);',
        '#endif',
        '        return this->coefficients[i];',
        '    }',
        '    /// Read a compact coefficient, checking the index when CHECK_BOUNDS is enabled.',
        '    CUDA_EXPORT Real const& operator[](int i) const {',
        '#ifdef CHECK_BOUNDS',
        '        DO_BOUNDS_CHECK(i);',
        '#endif',
        '        return this->coefficients[i];',
        '    }',
        '    /// Access a stored independent Cartesian component.',
        '    CUDA_EXPORT Real& operator()(int nx, int ny, int nz) {',
        ('        ASSERT(nz <= 1 || (degree >= 2 && nx == 0 && ny == 0 && nz == 2));'
         if quadrupoleTrace else '        ASSERT(nz <= 1);'),
        '        return (*this)[index(nx, ny, nz)];',
        '    }',
        '    /// Read a Cartesian component; ranks above two have zero trace.',
        '    CUDA_EXPORT Real operator()(int nx, int ny, int nz) const {',
        ('        if (nz < 2 || (degree >= 2 && nx == 0 && ny == 0 && nz == 2)) {'
         if quadrupoleTrace else '        if (nz < 2) {'),
        '            return (*this)[index(nx, ny, nz)];',
        '        }',
        '        return -(*this)(nx + 2, ny, nz - 2) - (*this)(nx, ny + 2, nz - 2);',
        '    }',
        '    /// Archive the independent coefficients in compact storage order.',
        '    template <class Archive> void serialize(Archive& arc, unsigned) {',
        '        for (auto& coefficient : this->coefficients) { arc & coefficient; }',
        '    }',
        '};',
        '} // namespace detail',
        'template <class Real, int order>',
        'struct Multipole : detail::Coefficients<Real, order - 2> {',
        '    static_assert(order >= 3 && order <= 9);',
        '    using detail::Coefficients<Real, order - 2>::operator=;',
        '};',
        'template <class Real, int order>',
        'struct Expansion : detail::Coefficients<Real, order - 1> {',
        '    static_assert(order >= 3 && order <= 9);',
        '    using detail::Coefficients<Real, order - 1>::operator=;',
        '};',
        'template <class Real, int order>',
        'struct Green : detail::Coefficients<Real, order - 1> {',
        '    static_assert(order >= 3 && order <= 9);',
        '    using detail::Coefficients<Real, order - 1>::operator=;',
        '};',
        'template <class Real, int order>',
        'using Derivatives = Green<Real, order>;',
        '} // namespace cosmictiger::gravity::cartesian', '',
    ]
    return '\n'.join(lines) + '\n'
