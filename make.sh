#!/usr/bin/env bash
set -x

directory="${1:-release}"

if [[ ! -d "$directory" ]]; then
    mkdir -p -- "$directory"
fi

cd -- "$directory" || exit 1
rm -f CMakeCache.txt

cmake \
    -DBUILD_TESTING=OFF \
    -DCMAKE_BUILD_TYPE="${directory^}" \
    -DCOSMICTIGER_DEVICE_PROFILE=ON \
    -DCOSMICTIGER_ENABLE_CHEMISTRY=OFF \
    -DCOSMICTIGER_ENABLE_FMM=ON \
    -DCOSMICTIGER_ENABLE_INTEGRATOR_GLOBAL=OFF \
    -DCOSMICTIGER_ENABLE_INTEGRATOR_HIERARCHICAL=ON \
    -DCOSMICTIGER_ENABLE_INTEGRATOR_TRADITIONAL=ON \
    -DCOSMICTIGER_ENABLE_PMMM_FMM=OFF \
    -DCOSMICTIGER_ENABLE_PMMM_PP=OFF \
    -DCOSMICTIGER_ENABLE_ROCKSTAR=OFF \
    -DCOSMICTIGER_ENABLE_SPH=ON \
    -DCOSMICTIGER_ENABLE_STARS=OFF \
    -DCOSMICTIGER_EXPANSION_DEGREE=5 \
    -DCOSMICTIGER_POSITION_TYPE=fixed32 \
    -DCOSMICTIGER_PROFILE=ON \
    -DCOSMICTIGER_REQUIRE_APEX=ON \
    -DCOSMICTIGER_WITH_CUDA=ON \
    -DCOSMICTIGER_WITH_LONG_LONG_PART_INT=ON \
    -DCOSMICTIGER_WITH_MAX_BUCKET=128 \
    -DHPX_DIR="$HOME/local/hpx/${directory^}/lib/cmake/HPX/" \
    ..
